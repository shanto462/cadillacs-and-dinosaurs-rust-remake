"""Writes a pseudo random input script (format: README.md, "Input scripts") for fights.

Usage: re/.venv/bin/python -I re/harness/genscript.py SEED FRAMES [--hits N] > re/harness/scripts/NAME.txt

Bouts of walking (a direction or two), then a burst of presses: A (punch chain), A with a direction (throw
when holding), J (jump), J then A (jump kick). Presses are 2 frames long and 6 or more frames apart (the game merges a
release of one frame). `--hits N` makes N out of 10 presses an attack (default 6).
"""
import random
import sys


def main():
    seed = int(sys.argv[1])
    frames = int(sys.argv[2])
    hits = 6
    if "--hits" in sys.argv:
        hits = int(sys.argv[sys.argv.index("--hits") + 1])
    rnd = random.Random(seed)
    dirs = ["R", "L", "U", "D", "RU", "RD", "LU", "LD"]
    out = [f"# generated by genscript.py seed {seed}, {frames} frames"]
    f = 0
    while f < frames:
        kind = rnd.randrange(10)
        if kind < 4:  # walk
            n = rnd.randrange(8, 40)
            out.append(f"{f}-{min(frames - 1, f + n - 1)}:{rnd.choice(dirs)}")
            f += n + 3
        elif kind < 4 + hits // 2 + 1:  # punch, maybe with a direction
            keys = "A" if rnd.randrange(3) else rnd.choice(["RA", "LA", "UA", "DA"])
            out.append(f"{f}-{f + 1}:{keys}")
            f += rnd.randrange(6, 14)
        elif kind < 9:  # jump or jump kick
            out.append(f"{f}-{f + 1}:J")
            if rnd.randrange(2):
                out.append(f"{f + 12}-{f + 13}:A")
            f += rnd.randrange(30, 45)
        else:  # wait
            f += rnd.randrange(5, 20)
    print("\n".join(out))


if __name__ == "__main__":
    main()
