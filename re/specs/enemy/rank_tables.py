# Decode rank / level / aggression tables (rank system 0x17F8A..0x18834)
import sys, struct
img = open(sys.argv[1], "rb").read()
B = lambda a, n: list(img[a:a+n])
Wd = lambda a, n: list(struct.unpack(f">{n}h", img[a:a+2*n]))
print("0x180B4 rank-init band thresholds on $4f6:", Wd(0x180b4, 3))
print("0x180BA row offsets [band*8 + dip]:"); 
for b in range(4): print("  band", b, [hex(x) for x in Wd(0x180ba + 16*b, 8)])
print("0x180FA initial-rank rows (value-1 = rank), 32 bytes each, row = offset/0x20:")
for r in range(10): print(f"  row {r} (+{r*0x20:#x})", B(0x180fa + 32*r, 32))
print("0x18094 initial aggression+1 per stage*4+area:", B(0x18094, 32))
print("0x1823A per-stage rank (delta, max, min, pad):", [Wd(0x1823a + 8*s, 4)[:3] for s in range(8)])
print("0x1860C level table [rank][players 1,2,3]:")
t = Wd(0x1860c, 96)
for r in range(32): print(f"  rank {r:2d}: {t[3*r:3*r+3]}")
print("0x187B8 rank-up period by speed index $5f6 0..15:", Wd(0x187b8, 16))
print("0x187D8..0x187DF consts:", [hex(x & 0xffff) for x in Wd(0x187d8, 4)])
print("0x187E0 rank drop on continue by DIP:", Wd(0x187e0, 8), " 0x187F0/F2:", Wd(0x187f0, 2))
print("0x187F4 rank-speed delta on continue [dip][players idx 0..3]:", [Wd(0x187f4 + 8*d, 4) for d in range(8)])
print("0x184C4 bonus-eval table:", B(0x184c4, 30))
for base in (0x182e4, 0x18364):
    print(f"aggression Markov table {base:#x} [cur 0..7][rand&15] -> next:")
    for c in range(8): print(f"  cur {c}:", B(base + 16*c, 16))
print("0x32566 rank-band random table (0x32540: [($5ee&0x18)*4 + rand&31] - 1):")
for b in range(4): print("  band", b, B(0x32566 + 32*b, 32))
